    private static readonly Dictionary<string, AnimationEmojiEntry> ByEmoji =
        Entries.ToDictionary(static entry => LookupKey(entry.Emoji), StringComparer.Ordinal);

    internal static AnimationEmojiEntry? Find(string? value) =>
        value is not null && ByEmoji.TryGetValue(LookupKey(value), out var entry) ? entry : null;

    // Optional emoji presentation selectors may be missing in older projects.
    private static string LookupKey(string value) => value.Trim().Replace("\uFE0F", "", StringComparison.Ordinal);
